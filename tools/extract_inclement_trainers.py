#!/usr/bin/env python3
"""Inclement Emerald's trainer teams as a Lua table for gen_trainer_teams.lua:
the sections of trainer_parties.h in order, each trainer constant with its
party (level relative to the player's best, species, held item, ability slot,
spread, moves), the spreads (EVs, IVs, nature) those parties name, and the
evolution table (to scale an evolved Pokemon back to its level).
Usage: extract_inclement_trainers.py > inclement_trainers.lua"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
DONOR = os.path.join(HERE, '../../../pokeemerald-1.13/src/data')

def read(name):
    return open(os.path.join(DONOR, name)).read()

# trainer constant -> party label and double flag
consts_of = {}
double = {}
for m in re.finditer(r'\[(TRAINER_\w+)\]\s*=\s*\{(.*?)\n    \},', read('trainers.h'), re.S):
    p = re.search(r'(sParty_\w+)', m.group(2))
    if not p: continue
    consts_of.setdefault(p.group(1), []).append(m.group(1)[len('TRAINER_'):])
    double[m.group(1)[len('TRAINER_'):]] = 'doubleBattle = TRUE' in m.group(2)

def mon(body):
    out = {}
    for key, val in re.findall(r'\.(\w+)\s*=\s*([^\n]*?),?\s*(?://[^\n]*)?\n', body + '\n'):
        val = val.strip().rstrip(',')
        if key == 'lvl': out['lvl'] = int(val)
        elif key == 'species': out['species'] = val.replace('SPECIES_', '')
        elif key == 'heldItem':
            if val != 'ITEM_NONE': out['item'] = val.replace('ITEM_', '')
        elif key == 'ability': out['ability'] = int(val)
        elif key == 'spread': out['spread'] = val
        elif key == 'moves':
            out['moves'] = [x.strip().replace('MOVE_', '') for x in val.split(',') if x.strip() and x.strip() != 'MOVE_NONE']
    return out

sections = []
parties = read('trainer_parties.h')
for m in re.finditer(r'^(// [^\n]*|static const struct TrainerMon\w* (sParty_\w+)\[\] = \{(.*?)\n\};)', parties, re.M | re.S):
    text = m.group(1)
    if text.startswith('//'):
        sections.append({'name': text[3:].strip(), 'trainers': []})
        continue
    label, body = m.group(2), m.group(3)
    mons = [mon(b) for b in re.findall(r'\n    \{(.*?)\n    \}', body, re.S)]
    mons = [x for x in mons if 'species' in x and 'lvl' in x]
    for const in consts_of.get(label, []):
        sections[-1]['trainers'].append({'const': const, 'double': double.get(const, False), 'party': mons})

spreads = {}
for m in re.finditer(r'\[(SPREAD_\w+)\]\s*=\s*\{(.*?)\n\t\},', read('trainer_spreads.h'), re.S):
    body = re.sub(r'//[^\n]*', '', m.group(2))
    def nums(field):
        f = re.search(r'\.' + field + r'\s*=\s*\{([^}]*)\}', body)
        vals = [int(x) for x in re.findall(r'\d+', f.group(1))] if f else []
        return (vals + [0] * 6)[:6]
    nat = re.search(r'\.nature\s*=\s*NATURE_(\w+)', body)
    # Inclement order: HP, Atk, Def, Spe, SpA, SpD
    ev, iv = nums('EVs'), nums('IVs')
    order = ['hp', 'atk', 'def', 'spe', 'spa', 'spd']
    spreads[m.group(1)] = {'evs': dict(zip(order, ev)), 'ivs': dict(zip(order, iv)),
                           'nature': nat.group(1) if nat else 'HARDY'}

evolutions = {}
for m in re.finditer(r'\[SPECIES_(\w+)\]\s*=\s*\{(.*?)\}\},', read('pokemon/evolution.h'), re.S):
    for method, param, target in re.findall(r'\{(EVO_\w+),\s*(\w+),\s*SPECIES_(\w+)', m.group(2) + '}'):
        evolutions.setdefault(m.group(1), []).append(
            {'method': method, 'param': int(param) if param.isdigit() else 0, 'into': target})

def lua(v, ind=''):
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return str(v)
    if isinstance(v, str): return json.dumps(v)
    if isinstance(v, list): return '{' + ', '.join(lua(x, ind) for x in v) + '}'
    return '{' + ', '.join('%s = %s' % (k if re.match(r'^[A-Za-z_]\w*$', k) else '[%s]' % json.dumps(k), lua(x, ind))
                           for k, x in v.items()) + '}'
print('-- Generated by tools/extract_inclement_trainers.py from pokeemerald-1.13 (Inclement Emerald).')
print('return {')
print('  sections = {')
for sec in sections: print('    ' + lua(sec) + ',')
print('  },')
print('  spreads = ' + lua(spreads) + ',')
print('  evolutions = ' + lua(evolutions) + ',')
print('}')
print('%d sections, %d trainers, %d spreads, %d evolving species' % (
    len(sections), sum(len(x['trainers']) for x in sections), len(spreads), len(evolutions)), file=sys.stderr)
